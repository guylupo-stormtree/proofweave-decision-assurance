"""Graphviz .dot export of the causality graph (DR-12). Deterministic output; run after timing.

The full graph groups each run's evidence; per-decision views (Stage 4) colour required items
covered (green) or missing (red). Rendering to SVG/PDF needs Graphviz (`dot -Tsvg graph.dot`).
"""
from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from .graph import InMemoryGraphStore

STYLE = {
    "run": 'shape=box, style="rounded,filled", fillcolor="#E8F0FB", color="#2B5797"',
    "verdict": 'shape=doubleoctagon, style=filled, fillcolor="#ECFDF5", color="#0F766E"',
    "function": 'shape=component, style=filled, fillcolor="#F4FBF9", color="#1F7A6B"',
    "value": 'shape=note, color="#555555"',
    "unit": 'shape=ellipse, color="#1F7A6B"',
    "chain": 'shape=hexagon, color="#5B3A9E"',
    "answer": 'shape=diamond, color="#5B3A9E"',
    "finding": 'shape=octagon, style=filled, fillcolor="#FDECEC", color="#A33B3B"',
    "scan": 'shape=box, color="#2B5797"',
    "decision": 'shape=box, style="filled,bold", fillcolor="#FFF7E6", color="#B45309"',
    "intent": 'shape=tab, style=filled, fillcolor="#F5F3FF", color="#5B3A9E"',
    "policy": 'shape=folder, style=filled, fillcolor="#F5F3FF", color="#5B3A9E"',
}


def _q(s: Any) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"') + '"'


def _label(n: dict[str, Any]) -> str:
    a = n["attrs"]
    k = n["kind"]
    if k == "run":
        g = "GREEN" if a.get("green") else ("not GREEN" if "green" in a else "")
        return f"{a.get('run')}\\n{a.get('requested_model') or ''} {g}".strip()
    if k == "function":
        return f"{a.get('name')}\\n{a.get('file') or 'unresolved'}"
    if k == "value":
        return f"{str(a.get('text'))[:40]}\\n{a.get('file')}:{a.get('line')}"
    if k == "unit":
        return f"unit {a.get('function')}\\n{str(a.get('source'))[:30]} @{a.get('line')}"
    if k == "decision":
        return f"decision {a.get('decision_id')}\\n{a.get('verdict')} · basis {a.get('basis_count')}"
    if k == "intent":
        return f"intent {a.get('intent_id')}\\n{a.get('action')} {a.get('repo')}@{str(a.get('commit'))[:10]}"
    if k == "policy":
        return f"policy {a.get('id')}@{a.get('version')}\\n{str(a.get('sha256'))[:12]}"
    if k == "answer":
        return f"reachable={a.get('reachable')}"
    return n["id"].split(":")[0] if k != "verdict" else n["id"].split(":", 1)[1]


def export(store: InMemoryGraphStore, path: Path, title: str, highlight: dict[str, str] | None = None) -> Path:
    """Write the graph to `path`. `highlight` maps node id -> colour (e.g. covered/missing items)."""
    snap = store.snapshot()
    lines = [f"// GENERATED by pwexp export_dot; graph sha256 {json.dumps(store.graph_hash())}",
             f"digraph {_q(title)} {{", '  rankdir=LR; fontname="Helvetica"; node [fontname="Helvetica", fontsize=10];',
             '  edge [fontname="Helvetica", fontsize=8, color="#777777"];', f"  label={_q(title)}; labelloc=t;"]
    for n in snap["nodes"]:
        extra = f', penwidth=3, color="{highlight[n["id"]]}"' if highlight and n["id"] in highlight else ""
        lines.append(f"  {_q(n['id'])} [label={_q(_label(n))}, {STYLE.get(n['kind'], 'shape=box')}{extra}];")
    for e in snap["edges"]:
        lab = e["kind"] + (f" {e['attrs']['i']}" if "i" in e["attrs"] else "") + \
              (f" {e['attrs']['label']}" if e["attrs"].get("label") else "")
        lines.append(f"  {_q(e['src'])} -> {_q(e['dst'])} [label={_q(lab)}];")
    lines.append("}")
    Path(path).write_text("\n".join(lines) + "\n")
    return Path(path)


def export_decision(store: InMemoryGraphStore, path: Path, decision_id: str) -> Path:
    """Decision view for figures (DR-23): decision, intent, policy, basis runs and what each run analysed."""
    root = f"decision:{decision_id}"
    if root not in store.nodes():
        raise KeyError(f"no decision {decision_id} in the graph")
    keep, edges = {root}, []
    for e in store.out_edges(root):
        keep.add(e["dst"])
        edges.append(e)
        if e["kind"] == "by":
            for u in store.out_edges(e["dst"], "observed"):
                keep.add(u["dst"])
                edges.append(u)
                for f in store.out_edges(u["dst"]):
                    if f["kind"] in ("about", "entered_from"):
                        keep.add(f["dst"])
                        edges.append(f)
    nodes = store.nodes()
    lines = [f"// GENERATED by pwexp export_dot (decision view); graph sha256 {json.dumps(store.graph_hash())}",
             f"digraph {_q(root)} {{", '  rankdir=LR; fontname="Helvetica"; node [fontname="Helvetica", fontsize=10];',
             '  edge [fontname="Helvetica", fontsize=8, color="#777777"];', f"  label={_q('decision ' + decision_id)}; labelloc=t;"]
    for nid in sorted(keep):
        n = nodes[nid]
        extra = ', penwidth=3' if nid == root else ""
        lines.append(f"  {_q(nid)} [label={_q(_label(n))}, {STYLE.get(n['kind'], 'shape=box')}{extra}];")
    for e in sorted(edges, key=lambda e: (e["src"], e["dst"], e["kind"])):
        lines.append(f"  {_q(e['src'])} -> {_q(e['dst'])} [label={_q(e['kind'])}];")
    lines.append("}")
    Path(path).write_text("\n".join(lines) + "\n")
    return Path(path)
